#!/usr/bin/env python3
"""q44_gen_equiv.py -- generate tools/q44_equiv.hip: standalone shipped-vs-lane-map
equivalence probe. Both kernels are EXTRACTED VERBATIM from src/r3d_gemm_mxfp4.hip
(no hand-copying: the probe measures the integrated code)."""
import re, sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "src/r3d_gemm_mxfp4.hip"
HDR = "src/r3d_mxfp4_q8x.h"
src = open(SRC).read()

def grab(anchor_start, stop_pat, name):
    i = src.index(anchor_start)
    m = re.compile(stop_pat, re.M).search(src, i)
    if not m: sys.exit(f"STOP PATTERN MISS for {name}")
    return src[i:m.end()]

f32b = grab("__device__ __forceinline__ uint16_t f32_to_bf16_m4", r"^\}\n", "f32_to_bf16_m4")
folds = grab("__device__ __forceinline__ uint32_t q8x_perm_x16",
             r"^    return c;\n\}\n", "fold kit")   # end of q8x_fold_f32
kA = grab("template <int MT>\n__global__ __launch_bounds__(32, 16) void gemm_nt_mxfp4_gemv_q8x_kernel(",
          r"^\}\n", "shipped q8x kernel")
kB = grab("template <int MT>\n__global__ __launch_bounds__(32, 16) void gemm_nt_mxfp4_gemv_q8x_lm_kernel(",
          r"^\}\n", "lane-map kernel")
# verify extraction actually contains both markers
assert "q8x_fold_i32(p, dpp);" in kA and "per-lane containment: NO fold" in kB
hdr = open(HDR).read()
hdr = hdr.replace('#ifndef R3D_MXFP4_Q8X_H', '// (inlined r3d_mxfp4_q8x.h)').replace('#define R3D_MXFP4_Q8X_H','')
hdr = hdr.replace('#endif /* R3D_MXFP4_Q8X_H */','')

harness = r"""
/* ===================== harness (generated by tools/q44_gen_equiv.py) ===================== */
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <cstdint>
#include <cmath>
#include <vector>
#include <hip/hip_runtime.h>

namespace {
__device__ __host__ inline float bf16_hi_f(uint16_t h) {
    uint32_t u = (uint32_t)h << 16; float f; memcpy(&f, &u, 4); return f;
}
}

static uint32_t rng_s = 0xC0FFEEu;
static uint32_t xrnd() { rng_s ^= rng_s << 13; rng_s ^= rng_s >> 17; rng_s ^= rng_s << 5; return rng_s; }

struct Res { int n_nan_split; int n_both_nan; double max_abs; double rel_l2_num; double rel_l2_den;
             int n_bit_exact; long n; };
static Res cmp(const std::vector<uint16_t>& a, const std::vector<uint16_t>& b) {
    Res r{0,0,0.0,0.0,0.0,0,(long)a.size()};
    double sa = 0.0;
    for (size_t i = 0; i < a.size(); ++i) {
        float x = bf16_hi_f(a[i]), y = bf16_hi_f(b[i]);
        if (a[i] == b[i]) ++r.n_bit_exact;
        bool nx = std::isnan(x), ny = std::isnan(y);
        if (nx != ny) { ++r.n_nan_split; continue; }
        if (nx && ny) { ++r.n_both_nan; continue; }
        double d = std::fabs((double)x - (double)y);
        if (d > r.max_abs) r.max_abs = d;
        r.rel_l2_num += d * d; sa += (double)x * x;
    }
    r.rel_l2_num = std::sqrt(r.rel_l2_num); r.rel_l2_den = std::sqrt(sa);
    return r;
}

static int launch_A(int mt, const void* S, const void* X, const void* SG, const void* AS, void* Y,
                    int M, int N, int K, int64_t yp, int64_t ap, int nt, int pf, int dpp) {
    #define L_(MT_) hipLaunchKernelGGL((gemm_nt_mxfp4_gemv_q8x_kernel<MT_>), dim3(N), dim3(32), 0, 0, \
        (const uint8_t*)S, (const int8_t*)X, (const float*)SG, (const float*)AS, (uint16_t*)Y, \
        M, N, K, yp, ap, nt, pf, dpp); return 0;
    switch (mt) { case 1: L_(1); case 2: L_(2); case 4: L_(4); default: L_(8); }
    #undef L_
}
static int launch_B(int mt, const void* S, const void* X, const void* SG, const void* AS, void* Y,
                    int M, int N, int K, int64_t yp, int64_t ap, int nt, int dpp) {
    #define L_(MT_) hipLaunchKernelGGL((gemm_nt_mxfp4_gemv_q8x_lm_kernel<MT_>), dim3(N), dim3(32), 0, 0, \
        (const uint8_t*)S, (const int8_t*)X, (const float*)SG, (const float*)AS, (uint16_t*)Y, \
        M, N, K, yp, ap, nt, dpp); return 0;
    switch (mt) { case 1: L_(1); case 2: L_(2); case 4: L_(4); default: L_(8); }
    #undef L_
}

static void ck(hipError_t e, const char* w) { if (e != hipSuccess) { fprintf(stderr, "HIP FAIL %s: %s\n", w, hipGetErrorName(e)); exit(2); } }

int main(int argc, char** argv) {
    const int N = 96;
    const int Ks[] = { 256, 1024, 1280, 1536, 1792, 2816, 2048, 8192 };
    const int Ms[] = { 1, 2, 4, 5, 6, 7, 8 };
    int fails = 0, exact_int_witness = 1;

    for (int K : Ks) for (int M : Ms) {
        const int mt = M >= 8 ? 8 : M >= 4 ? 4 : M >= 2 ? 2 : 1;
        const int64_t plane = (int64_t)N * (K >> 7) * 136;
        std::vector<uint8_t> hS(plane);
        std::vector<int8_t>  hX((int64_t)M * K);
        std::vector<float>   hSG((int64_t)M * (K >> 5)), hAS((int64_t)M * (K / 128 + 4));
        const int64_t yp = N, ap = K / 128 + 4;

        for (int mode = 0; mode < 3; ++mode) {   /* 0=random 1=torture 2=int-exact */
            if (mode == 0) {
                for (auto& b : hS) b = (uint8_t)xrnd();
                /* keep scales mostly in a sane band for mode 0, torture in 1 */
                for (auto& b : hX) b = (int8_t)(xrnd() & 0xFF);
                for (auto& f : hSG) f = (float)((xrnd() & 0xFFFF) / 32768.0 - 1.0);
                for (auto& f : hAS) f = (float)((xrnd() & 0xFFFF) / 32768.0 - 1.0);
            } else if (mode == 1) {
                static const uint8_t sb[] = { 0x00, 0x01, 0x7F, 0x80, 0xFE, 0xFF };
                static const int8_t  xb[] = { 0, 1, -1, 127, -128, 12, -12 };
                for (size_t i = 0; i < hS.size(); ++i) {
                    /* header bytes (first 8 of every 136) get scale torture, rest codes */
                    if (i % 136 < 8) hS[i] = sb[xrnd() % 6];
                    else hS[i] = (uint8_t)(xrnd() & 0xFF);   /* full i8 incl 0x80 */
                }
                for (auto& b : hX) b = xb[xrnd() % 7];
                for (auto& f : hSG) f = (xrnd() & 1) ? 3.4e38f : 1.18e-38f;
                for (auto& f : hAS) f = (xrnd() & 1) ? -2.0f : 0.5f;
            } else {
                for (auto& b : hS) b = 127;                  /* sc = 2^0 */
                for (size_t i = 0; i < hS.size(); ++i)
                    if (i % 136 >= 8) hS[i] = (uint8_t)(xrnd() % 4);   /* codes 0..3 */
                for (auto& b : hX) b = (int8_t)(xrnd() % 2);           /* 0/1 */
                for (auto& f : hSG) f = 1.0f;
                for (auto& f : hAS) f = 1.0f;
            }

            uint8_t *dS; int8_t *dX; float *dSG, *dAS; uint16_t *dYa, *dYb;
            ck(hipMalloc(&dS, plane), "S"); ck(hipMalloc(&dX, hX.size()), "X");
            ck(hipMalloc(&dSG, hSG.size() * 4), "SG"); ck(hipMalloc(&dAS, hAS.size() * 4), "AS");
            ck(hipMalloc(&dYa, (size_t)yp * M * 2), "Ya"); ck(hipMalloc(&dYb, (size_t)yp * M * 2), "Yb");
            ck(hipMemcpy(dS, hS.data(), plane, hipMemcpyHostToDevice), "cpS");
            ck(hipMemcpy(dX, hX.data(), hX.size(), hipMemcpyHostToDevice), "cpX");
            ck(hipMemcpy(dSG, hSG.data(), hSG.size() * 4, hipMemcpyHostToDevice), "cpSG");
            ck(hipMemcpy(dAS, hAS.data(), hAS.size() * 4, hipMemcpyHostToDevice), "cpAS");

            for (int nt : {0, 1}) for (int dpp : {0, 1, 2}) {
                if (mode == 1 && !(nt == 1 && dpp == 1)) continue;   /* torture: default combo only */
                if (mode == 2 && !(nt == 1 && (dpp == 1 || dpp == 0))) continue;
                launch_A(mt, dS, dX, dSG, dAS, dYa, M, N, K, yp, ap, nt, 1, dpp);
                launch_B(mt, dS, dX, dSG, dAS, dYb, M, N, K, yp, ap, nt, dpp);
                ck(hipDeviceSynchronize(), "sync");
                std::vector<uint16_t> Ya((size_t)yp * M), Yb((size_t)yp * M);
                ck(hipMemcpy(Ya.data(), dYa, Ya.size() * 2, hipMemcpyDeviceToHost), "cpYa");
                ck(hipMemcpy(Yb.data(), dYb, Yb.size() * 2, hipMemcpyDeviceToHost), "cpYb");
                Res r = cmp(Ya, Yb);
                double rl2 = r.rel_l2_den > 0 ? r.rel_l2_num / r.rel_l2_den : r.rel_l2_num;
                printf("MODE=%d K=%d M=%d mt=%d nt=%d dpp=%d | bitexact=%ld/%ld maxabs=%.6g rel_l2=%.3g nan_split=%d both_nan=%d\n",
                       mode, K, M, mt, nt, dpp, (long)r.n_bit_exact, r.n, r.max_abs, rl2,
                       r.n_nan_split, r.n_both_nan);
                if (r.n_nan_split) { fprintf(stderr, "HARD FAIL (NaN split)\n"); ++fails; }
                if (mode == 2 && (long)r.n_bit_exact != r.n) {
                    fprintf(stderr, "INT-EXACT WITNESS FAIL: mode-2 outputs not bit-identical\n");
                    ++fails; exact_int_witness = 0;
                }
                if (mode != 2 && rl2 > 3e-2) { fprintf(stderr, "TOLERANCE FAIL rel_l2>3e-2\n"); ++fails; }
            }
            hipFree(dS); hipFree(dX); hipFree(dSG); hipFree(dAS); hipFree(dYa); hipFree(dYb);
        }
    }
    printf("EQUIV %s (fails=%d int_exact_witness=%s)\n", fails ? "FAIL" : "PASS", fails,
           exact_int_witness ? "BIT-IDENTICAL" : "NOT-IDENTICAL");
    return fails ? 1 : 0;
}
"""

out = ("// q44_equiv.hip -- GENERATED by tools/q44_gen_equiv.py; do not hand-edit.\n"
       "// Shipped q8x walk vs lane-map walk arm-for-arm on the SAME inputs.\n"
       "#include <cstdint>\n#include <cstring>\n#include <cmath>\n#include <hip/hip_runtime.h>\n"
       + hdr + "\nnamespace {\n" + f32b + folds + "\n" + kA + "\n" + kB + "} /* anon */\n" + harness)
open("tools/q44_equiv.hip", "w").write(out)
print(f"wrote tools/q44_equiv.hip ({len(out.splitlines())} lines)")
